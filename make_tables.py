#!/usr/bin/env python3
"""Writes tables.h for lock.c from the values in keycalc.py, so no constant is typed by hand."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "reference"))
import keycalc as k

def limbs(n):                       # 256-bit number -> 16 little-endian 16-bit pieces
    return ",".join(f"0x{(n >> (16 * i)) & 0xFFFF:04X}" for i in range(16))
def u32s(vals, per=4):
    v = [f"0x{x:08X}UL" for x in vals]
    return ",\n ".join(",".join(v[i:i + per]) for i in range(0, len(v), per))
def u64s(vals):
    return ",\n ".join(f"{{0x{x >> 32:08X}UL,0x{x & 0xFFFFFFFF:08X}UL}}" for x in vals)
def table(t):
    return ",\n ".join("{" + ",".join(map(str, row)) + "}" for row in t)

words = k.load_words()
out = f"""/* tables.h - generated by make_tables.py from keycalc.py. Do not edit. */
static const u32 K256[64] = {{\n {u32s(k.K256)} }};
static const u32 H256[8] = {{\n {u32s(k.H256)} }};
static const u64 K512[80] = {{\n {u64s(k.K512)} }};
static const u64 H512[8] = {{\n {u64s(k.H512)} }};
static const u8 RL[5][16] = {{\n {table(k._RL)} }};
static const u8 RR[5][16] = {{\n {table(k._RR)} }};
static const u8 SL[5][16] = {{\n {table(k._SL)} }};
static const u8 SR[5][16] = {{\n {table(k._SR)} }};
static const u32 KL[5] = {{ {u32s(k._KL, 5)} }};
static const u32 KR[5] = {{ {u32s(k._KR, 5)} }};
static const u16 FP[16] = {{ {limbs(k.P)} }};        /* the field prime */
static const u16 FP2[16] = {{ {limbs(k.P - 2)} }};   /* prime - 2, for division */
static const u16 FN[16] = {{ {limbs(k.N)} }};        /* the curve order */
static const u16 GX[16] = {{ {limbs(k.GX)} }};
static const u16 GY[16] = {{ {limbs(k.GY)} }};
static const char WORDS[2048][9] = {{
"""
out += ",\n".join(",".join(f'"{w}"' for w in words[i:i + 8]) for i in range(0, 2048, 8)) + " };\n"
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables.h"), "w").write(out)
